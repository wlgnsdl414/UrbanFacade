def colorize_coco(mask: np.ndarray) -> np.ndarray:
    h, w = mask.shape
    colored = np.zeros((h, w, 3), dtype=np.uint8)
    for label in np.unique(mask):
        if label < len(coco_colormap):
            colored[mask == label] = coco_colormap[label]
    return colored

