scaler = amp.GradScaler(device="cuda")

def train(model, loader, opt, criterion, device, epoch=None, total_epochs=None):
    model.train()
    total = 0
    loop = tqdm(loader, desc=f"Training Epoch {epoch+1}/{total_epochs}" if epoch is not None else "Training", leave=True)
    for x,y,_ in loop:
        x,y = x.to(device), y.to(device)
        opt.zero_grad()

        with amp.autocast("cuda"):
          out  = model(x)
          loss = criterion(out,y)

        scaler.scale(loss).backward()
        scaler.step(opt)
        scaler.update()

        total += loss.item()*x.size(0)
    return total/len(loader.dataset)

def evaluate(model, loader, criterion, device, epoch=None, total_epochs=None):
    model.eval()
    hist = np.zeros((num_classes, num_classes))
    total_loss = 0
    n = 0
    loop = tqdm(loader, desc=f"Validating Epoch {epoch+1}/{total_epochs}" if epoch is not None else "Validating", leave=False)
    with torch.no_grad():
        for x,y,_ in loop:
            with amp.autocast("cuda"):
                out = model(x.to(device))
                loss = criterion(out, y.to(device))
            total_loss += loss.item()*x.size(0)
            n += x.size(0)
            pred = out.argmax(1).cpu().numpy()
            gt = y.numpy()
            mask = (gt>=0) & (gt<num_classes)
            hist += np.bincount(num_classes*gt[mask]+pred[mask], minlength=num_classes**2).reshape(num_classes, num_classes)
    iu = np.diag(hist)/(hist.sum(1)+hist.sum(0)-np.diag(hist)+1e-6)
    avg_loss = total_loss/max(n, 1)
    return avg_loss, np.nanmean(iu), hist

