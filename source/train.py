def save_checkpoint(epoch, model, optimizer, ckpt_dir):
    os.makedirs(ckpt_dir, exist_ok=True)
    save_path = os.path.join(ckpt_dir, f"epoch_{epoch+1}.pth")
    torch.save({
        'epoch': epoch,
        'model_state_dict': model.state_dict(),
        'optimizer_state_dict': optimizer.state_dict()
    }, save_path)

def load_checkpoint(model, optimizer, ckpt_dir):
    if not os.path.exists(ckpt_dir):
        os.makedirs(ckpt_dir, exist_ok=True)
        return 0

    ckpts = sorted([f for f in os.listdir(ckpt_dir) if f.endswith(".pth")])
    if not ckpts:
        print("No checkpoint found. Generating a new checkpoint.")
        return 0

    latest_ckpt = os.path.join(ckpt_dir, ckpts[-1])
    ckpt = torch.load(latest_ckpt)
    model.load_state_dict(ckpt['model_state_dict'])
    optimizer.load_state_dict(ckpt['optimizer_state_dict'])
    start_epoch = ckpt['epoch']+1
    print(f"Resumed from {latest_ckpt} (epoch {start_epoch})")
    return start_epoch

