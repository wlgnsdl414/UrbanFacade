# Model metrics
# -------------------------------------------------------------------------
def model_metrics(hist):
    acc = np.diag(hist).sum()/hist.sum()
    iu = np.diag(hist)/(hist.sum(1)+hist.sum(0)-np.diag(hist)+1e-6)
    mean_iu = np.nanmean(iu)
    f1 = 2*np.diag(hist)/(hist.sum(1)+hist.sum(0)+1e-6)
    return acc, mean_iu, iu, f1

# -------------------------------------------------------------------------
# Loss function
# -------------------------------------------------------------------------
def dice_loss(logits, target, eps=1e-6):
    probs = F.softmax(logits, dim=1)
    target_oh = F.one_hot(target, num_classes=logits.shape[1]).permute(0, 3, 1, 2).float()
    inter = torch.sum(probs*target_oh, dim=(0, 2, 3))
    card  = torch.sum(probs+target_oh, dim=(0, 2, 3))
    dice = (2*inter+eps)/(card+eps)
    return 1-dice.mean()

